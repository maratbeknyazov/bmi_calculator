// Импортируем "набор инструментов" для создания интерфейса (кнопки, цвета, шрифты)
import 'package:bmi_calculator/constants.dart'; // Берем константы (например, цвет нижней панели)
import 'package:flutter/material.dart'; // Основная библиотека Flutter для дизайна

// Мы создаем свой собственный "кирпичик" (виджет) под названием BottomButton.
// StatelessWidget означает, что кнопка сама по себе не меняется (не перекрашивается на лету), 
// она просто отображает то, что ей велели.
class BottomButton extends StatelessWidget {
  
  // Конструктор: это правила, по которым создается кнопка.
  // Мы говорим: "Эй, чтобы я появилась, дай мне текст и скажи, что делать при нажатии!"
  const BottomButton({
    Key? key, 
    required this.text, // Нам обязательно нужна строка текста (например, "РАССЧИТАТЬ")
    required this.tap,  // Нам обязательно нужна функция (команда), что делать при клике
  }) : super(key: key);

  // Это "кармашки", где хранятся данные, которые мы передали выше
  final String text;         // Тут лежит само слово
  final VoidCallback tap;    // Тут лежит "инструкция по нажатию"

  // Метод build — это чертеж, по которому Flutter рисует кнопку на экране
  @override
  Widget build(BuildContext context) {
    // GestureDetector — это невидимый слой, который "чувствует" касание пальца
    return GestureDetector(
      onTap: tap, // Когда палец коснулся — выполняем ту самую команду 'tap'
      
      // Container — это просто коробочка, в которую мы упаковываем нашу кнопку
      child: Container(
        margin: const EdgeInsets.only(top: 15.0), // Делаем небольшой отступ сверху, чтобы не прилипало
        color: kBottomColor, // Красим коробочку в цвет из нашего файла констант
        height: 50.0, // Высота кнопки (в логических пикселях)
        width: double.infinity, // Растягиваем кнопку на всю ширину экрана
        
        // Center — выравнивает содержимое (текст) ровно по центру коробочки
        child: Center(
          child: Text(
            text, // Выводим тот самый текст, который передали в начале
            style: const TextStyle(
              fontSize: 20.0, // Размер букв
              fontWeight: FontWeight.w500, // Жирность шрифта (средняя)
            ),
          ),
        ),
      ),
    );
  }
}